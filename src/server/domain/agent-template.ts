export const agentChangeSchema = z
  .object({
    action: z.enum(["KEEP", "CREATE", "UPDATE"]),
    kind: z.enum(
      Object.keys(AGENT_FIELDS) as [
        keyof typeof AGENT_FIELDS,
        ...(keyof typeof AGENT_FIELDS)[],
      ],
    ),
    id: z.uuid().optional(),
    expectedVersion: z.number().int().positive().optional(),
    values: z.record(z.string(), z.unknown()),
    reason: z.string().max(2000),
  })
  .strict();
export const agentTemplateSchema = z
  .object({
    format: z.literal("mct-agent/1"),
    programId: z.uuid(),
    exportedAt: z.iso.datetime(),
    changes: z.array(agentChangeSchema).max(2000),
  })
  .strict();
export type AgentTemplate = z.infer<typeof agentTemplateSchema>;
