import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const files = (await readdir("db/migrations"))
  .filter((n) => n.endsWith(".sql"))
  .sort();
const manifest = [];
for (const name of files)
  manifest.push({
    name,
    hash: createHash("sha256")
      .update(await readFile(`db/migrations/${name}`))
      .digest("hex"),
  });
await writeFile(
  "src/server/infrastructure/schema-manifest.ts",
  `// Generated by scripts/generate-schema-manifest.ts; never edit applied SQL.\nexport const SCHEMA_MANIFEST=${JSON.stringify(manifest, null, 2)} as const;\n`,
);
